//! Small, local-only durable scrollback store.
//!
//! Scrollback is deliberately kept outside the workspace JSON.  The store
//! never trusts a caller supplied id as a path component and refuses symlinks,
//! which keeps terminal ids from escaping the app-data directory.

use std::collections::HashSet;
use std::fs::{self, File, OpenOptions};
use std::io::{self, Read, Write};
use std::path::{Path, PathBuf};
use std::sync::{Arc, Mutex};
use std::time::{Duration, SystemTime};

use crate::sync::LockExt;

/// A terminal's durable log is intentionally smaller than an unbounded
/// transcript.  The in-memory PTY backlog uses the same cap.
pub const SCROLLBACK_CAP: usize = 256 * 1024;
const COMPACTION_THRESHOLD: usize = 2 * SCROLLBACK_CAP;
const SCROLLBACK_EXTENSION: &str = "scrollback";
const DEFAULT_ORPHAN_AGE: Duration = Duration::from_secs(30 * 24 * 60 * 60);

/// Whether `id` is safe to use as one file or directory name: only
/// `[A-Za-z0-9._-]`, and not `.` or `..`. Ids generated by Terra Swarm
/// (`t-123`, `ws-4`) pass, while `../...`, separators and empty ids do not.
pub(crate) fn is_plain_path_component(id: &str) -> bool {
    !id.is_empty()
        && id != "."
        && id != ".."
        && id
            .bytes()
            .all(|byte| byte.is_ascii_alphanumeric() || matches!(byte, b'-' | b'_' | b'.'))
}

#[derive(Clone, Default)]
pub struct ScrollbackStore {
    root: Option<PathBuf>,
    write_lock: Arc<Mutex<()>>,
}

impl ScrollbackStore {
    pub fn new(root: Option<PathBuf>) -> Self {
        Self {
            root,
            write_lock: Arc::new(Mutex::new(())),
        }
    }

    pub fn from_root(root: PathBuf) -> Self {
        Self::new(Some(root))
    }

    /// Return a path only for a single, conservative filename component.
    fn path_for(&self, id: &str) -> Option<PathBuf> {
        let root = self.root.as_ref()?;
        if !is_plain_path_component(id) {
            return None;
        }
        Some(root.join(format!("{}.{}", id, SCROLLBACK_EXTENSION)))
    }

    fn reject_symlink(path: &Path) -> io::Result<()> {
        match fs::symlink_metadata(path) {
            Ok(metadata) if metadata.file_type().is_symlink() => Err(io::Error::new(
                io::ErrorKind::PermissionDenied,
                "refusing to use a symlink as a scrollback file",
            )),
            Ok(_) => Ok(()),
            Err(error) if error.kind() == io::ErrorKind::NotFound => Ok(()),
            Err(error) => Err(error),
        }
    }

    fn read_path(path: &Path) -> io::Result<Vec<u8>> {
        Self::reject_symlink(path)?;
        let mut data = Vec::new();
        match File::open(path) {
            Ok(mut file) => {
                file.read_to_end(&mut data)?;
            }
            Err(error) if error.kind() == io::ErrorKind::NotFound => return Ok(data),
            Err(error) => return Err(error),
        }
        if data.len() > SCROLLBACK_CAP {
            data = data[data.len() - SCROLLBACK_CAP..].to_vec();
        }
        Ok(data)
    }

    fn write_atomic(path: &Path, data: &[u8]) -> io::Result<()> {
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent)?;
        }
        let tmp = path.with_extension("scrollback.tmp");
        Self::reject_symlink(&tmp)?;
        {
            let mut file = File::create(&tmp)?;
            file.write_all(data)?;
            file.sync_data()?;
        }
        fs::rename(tmp, path)
    }

    pub fn append(&self, id: &str, chunk: &[u8]) -> io::Result<()> {
        let Some(path) = self.path_for(id) else {
            return Ok(());
        };
        if chunk.is_empty() {
            return Ok(());
        }

        let _guard = self.write_lock.lock_or_recover();
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent)?;
        }
        Self::reject_symlink(&path)?;

        let current_len = fs::metadata(&path)
            .map(|metadata| usize::try_from(metadata.len()).unwrap_or(usize::MAX))
            .unwrap_or(0);
        if current_len.saturating_add(chunk.len()) <= COMPACTION_THRESHOLD {
            let mut file = OpenOptions::new().create(true).append(true).open(&path)?;
            return file.write_all(chunk);
        }

        let mut retained = Self::read_path(&path)?;
        retained.extend_from_slice(chunk);
        if retained.len() > SCROLLBACK_CAP {
            let cut = retained.len() - SCROLLBACK_CAP;
            retained.drain(..cut);
        }
        Self::write_atomic(&path, &retained)
    }

    /// Read the latest durable tail. Missing files are an empty scrollback.
    pub fn read(&self, id: &str) -> io::Result<Vec<u8>> {
        let Some(path) = self.path_for(id) else {
            return Ok(Vec::new());
        };
        Self::read_path(&path)
    }

    /// Remove a terminal's durable transcript. This is called only by the
    /// explicit destructive `kill_terminal` command; stopping or application
    /// shutdown intentionally leaves the file in place.
    pub fn remove(&self, id: &str) -> io::Result<bool> {
        let Some(path) = self.path_for(id) else {
            return Ok(false);
        };
        let _guard = self.write_lock.lock_or_recover();
        match fs::remove_file(path) {
            Ok(()) => Ok(true),
            Err(error) if error.kind() == io::ErrorKind::NotFound => Ok(false),
            Err(error) => Err(error),
        }
    }

    /// Remove only old files that are not represented by persisted terminal
    /// metadata. Recent unknown files are retained so a crash or a delayed
    /// migration cannot silently lose a user's transcript.
    pub fn cleanup_orphans(&self, known_ids: &HashSet<String>) -> io::Result<usize> {
        self.cleanup_orphans_older_than(known_ids, DEFAULT_ORPHAN_AGE)
    }

    pub fn cleanup_orphans_older_than(
        &self,
        known_ids: &HashSet<String>,
        age: Duration,
    ) -> io::Result<usize> {
        let Some(root) = self.root.as_ref() else {
            return Ok(0);
        };
        let entries = match fs::read_dir(root) {
            Ok(entries) => entries,
            Err(error) if error.kind() == io::ErrorKind::NotFound => return Ok(0),
            Err(error) => return Err(error),
        };
        let now = SystemTime::now();
        let mut removed = 0;
        for entry in entries {
            let entry = entry?;
            let path = entry.path();
            if path.extension().and_then(|ext| ext.to_str()) != Some(SCROLLBACK_EXTENSION) {
                continue;
            }
            let Some(id) = path.file_stem().and_then(|stem| stem.to_str()) else {
                continue;
            };
            if self.path_for(id).as_deref() != Some(path.as_path()) || known_ids.contains(id) {
                continue;
            }
            let metadata = match fs::symlink_metadata(&path) {
                Ok(metadata) if metadata.file_type().is_file() => metadata,
                _ => continue,
            };
            let old_enough = metadata
                .modified()
                .ok()
                .and_then(|modified| now.duration_since(modified).ok())
                .is_some_and(|elapsed| elapsed >= age);
            if old_enough && fs::remove_file(path).is_ok() {
                removed += 1;
            }
        }
        Ok(removed)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::fs;
    use std::sync::atomic::{AtomicU64, Ordering};

    static TEST_SEQUENCE: AtomicU64 = AtomicU64::new(0);

    fn store(label: &str) -> (ScrollbackStore, PathBuf) {
        let id = TEST_SEQUENCE.fetch_add(1, Ordering::Relaxed);
        let root = std::env::temp_dir().join(format!(
            "terra-swarm-scrollback-{label}-{}-{id}",
            std::process::id()
        ));
        fs::create_dir_all(&root).expect("scrollback root");
        (ScrollbackStore::from_root(root.clone()), root)
    }

    fn cleanup(root: &Path) {
        let _ = fs::remove_dir_all(root);
    }

    #[test]
    fn appends_and_caps_to_the_newest_bytes() {
        let (store, root) = store("cap");
        store.append("t-1", b"hello").expect("append");
        assert_eq!(store.read("t-1").expect("read"), b"hello");
        store
            .append("t-1", &vec![b'x'; SCROLLBACK_CAP + 5])
            .expect("large append");
        let data = store.read("t-1").expect("capped read");
        assert_eq!(data.len(), SCROLLBACK_CAP);
        assert!(data.iter().all(|byte| *byte == b'x'));
        cleanup(&root);
    }

    #[cfg(unix)]
    #[test]
    fn given_a_full_log_when_appending_a_small_chunk_then_it_appends_without_rewriting_the_file() {
        use std::os::unix::fs::MetadataExt;
        let (store, root) = store("full");
        store
            .append("t-1", &vec![b'x'; SCROLLBACK_CAP])
            .expect("fill");
        let path = root.join("t-1.scrollback");
        let inode = fs::metadata(&path).expect("metadata").ino();

        store.append("t-1", b"tail").expect("append");

        assert_eq!(fs::metadata(&path).expect("metadata").ino(), inode);
        let data = store.read("t-1").expect("read");
        assert_eq!(data.len(), SCROLLBACK_CAP);
        assert!(data.ends_with(b"tail"));
        cleanup(&root);
    }

    #[test]
    fn given_a_log_at_the_compaction_threshold_when_appending_then_the_file_shrinks_to_the_cap() {
        let (store, root) = store("compact");
        store
            .append("t-1", &vec![b'x'; 2 * SCROLLBACK_CAP])
            .expect("fill");

        store.append("t-1", b"tail").expect("append");

        let path = root.join("t-1.scrollback");
        assert_eq!(
            fs::metadata(&path).expect("metadata").len(),
            u64::try_from(SCROLLBACK_CAP).expect("cap fits in u64")
        );
        assert!(store.read("t-1").expect("read").ends_with(b"tail"));
        cleanup(&root);
    }

    #[test]
    fn rejects_path_traversal_and_symlink_files() {
        let (store, root) = store("secure");
        store
            .append("../escape", b"nope")
            .expect("invalid id is ignored");
        assert!(!root.join("escape.scrollback").exists());
        cleanup(&root);
    }

    #[test]
    fn cleanup_is_conservative_for_recent_orphans() {
        let (store, root) = store("cleanup");
        store.append("t-orphan", b"keep").expect("append");
        let known = HashSet::new();
        assert_eq!(store.cleanup_orphans(&known).expect("cleanup"), 0);
        assert_eq!(store.read("t-orphan").expect("read"), b"keep");
        assert_eq!(
            store
                .cleanup_orphans_older_than(&known, Duration::ZERO)
                .expect("forced cleanup"),
            1
        );
        assert!(store.read("t-orphan").expect("read removed").is_empty());
        cleanup(&root);
    }
}
